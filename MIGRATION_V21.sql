-- ══════════════════════════════════════════════════════════
-- MIGRATION V21 — عرض PIN الزبون بشكل متكرر للموظف
-- ══════════════════════════════════════════════════════════
-- المشكلة: عمود client_pin يخزّن نسخة مُجزَّأة (hash) أحادية الاتجاه
-- من رمز PIN — نفس مبدأ كلمة المرور — لا يمكن فك تشفيرها لعرضها
-- للموظف بعد أول مرة. هذا صحيح أمنياً لكنه غير عملي لموظف يحتاج
-- إعطاء الزبون رقمه أكثر من مرة.
--
-- الحل: عمود إضافي client_pin_plain يخزّن نص PIN صراحةً، يُستخدم
-- فقط لعرضه/نسخه للموظف من داخل نافذة تعديل الحساب. تسجيل دخول
-- الزبون في بوابته يستمر بالاعتماد حصرياً على client_pin المُجزَّأ
-- — لا تغيير على أمان تسجيل الدخول.
--
-- ⚠️ ملاحظة أمنية: هذا يعني أن أي شخص يملك وصولاً لقاعدة البيانات
-- (أو صلاحية أدمن في النظام) يستطيع رؤية PIN كل الزبائن نصياً.
-- هذا مقبول لأن الـ PIN هنا وسيلة دخول لعرض كشف حساب فقط (ليس
-- كلمة مرور حساس مثل حساب بنكي)، لكن إن غيّرت رأيك لاحقاً يمكن
-- حذف هذا العمود والعودة للسلوك القديم (توليد PIN جديد كل مرة).
-- ══════════════════════════════════════════════════════════

ALTER TABLE public.accounts
  ADD COLUMN IF NOT EXISTS client_pin_plain text DEFAULT NULL;

COMMENT ON COLUMN public.accounts.client_pin_plain IS
  'نص PIN الزبون الصريح — لعرضه فقط في واجهة الموظف، غير مستخدم في تسجيل الدخول';

-- ══ اكتشاف جانبي أثناء هذا الإصلاح ═══════════════════════════
-- MIGRATION_V7 وضعت أرقام PIN نصية صريحة (مثال: '048213') مباشرة
-- في client_pin عند إنشاء العمود لأول مرة، لكن كود تسجيل الدخول
-- الحالي يقارن client_pin بنسخة مُجزَّأة SHA-256 — أي حساب لم
-- يُولَّد له PIN جديد منذ ذلك الحين (زر "🔄 PIN جديد") لن يستطيع
-- الدخول لبوابته أبداً بذلك الرقم القديم لأن المقارنة ستفشل دوماً.
-- نصحح هذا هنا: أي client_pin ما زال 6 أرقام صريحة (وليس hash) —
-- نحفظه في client_pin_plain للعرض، ثم نجزّئه بنفس أسلوب النظام.
UPDATE public.accounts
SET client_pin_plain = client_pin,
    client_pin = encode(extensions.digest(client_pin, 'sha256'), 'hex')
WHERE type = 'customer'
  AND client_pin ~ '^[0-9]{6}$';
