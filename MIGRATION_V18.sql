-- الهدف: ضمان وجود عمود created_at في جدول accounts
--        (مطلوب لميزة "الترتيب حسب تاريخ الإنشاء" في accounts.html)
--
-- ملاحظة مهمة: السكيمة الأساسية لجدول accounts لم تُسجَّل بالكامل
-- في ملفات الـ migration السابقة، لذلك لا يمكن التأكيد ببساطة
-- أن هذا العمود موجود مسبقاً. هذا السكربت آمن للتشغيل في كل الحالات:
-- إن كان العمود موجوداً لن يحدث أي تغيير، وإن لم يكن موجوداً
-- سيُضاف بقيمة افتراضية "الآن" للحسابات الحالية.
-- ══════════════════════════════════════════════════

ALTER TABLE accounts
  ADD COLUMN IF NOT EXISTS created_at timestamptz DEFAULT now();

-- تعبئة created_at للحسابات القديمة التي قد يكون العمود فيها NULL
-- (مثلاً إن كان العمود مضافاً حديثاً في السطر أعلاه بدون DEFAULT وقت الإنشاء الفعلي)
UPDATE accounts SET created_at = now() WHERE created_at IS NULL;
