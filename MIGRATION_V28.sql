-- إضافة عمود لقالب رسالة "مطابقة الأرصدة" التي يُنسخها زر المطابقة
-- في حسابات الشركات. نستخدم نفس جدول print_assets الموجود أصلاً
-- (الشعار/الختم/التوقيع) لأنه فعليًا "إعدادات المستندات المطبوعة
-- والمراسلات" — مكان واحد منطقي لكل هذه الإعدادات معًا.
--
-- إن تُرك فارغًا (NULL)، تستخدم الواجهة قالبًا افتراضيًا مدمجًا
-- في الكود (ليس بحاجة لإدخال بيانات لتعمل الميزة فورًا).
-- ══════════════════════════════════════════════════════════

ALTER TABLE public.print_assets
  ADD COLUMN IF NOT EXISTS reconciliation_msg text DEFAULT NULL;

COMMENT ON COLUMN public.print_assets.reconciliation_msg IS
  'قالب رسالة مطابقة الأرصدة (نص حر مع عناصر نائبة مثل {company_name})، NULL = استخدام القالب الافتراضي في الواجهة';
